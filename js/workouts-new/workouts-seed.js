// ============================================
// 🏋️ НАЧАЛЬНЫЕ ДАННЫЕ УПРАЖНЕНИЙ
// ============================================
// Заполняет WorkoutStore базовыми упражнениями
// и вариантами для быстрого старта.
// ============================================
"use strict";

function seedWorkoutData() {
  // Если данные уже есть — не заполняем
  if (WorkoutStore.getBaseExercises().length > 0) {
    console.log('[seed] WorkoutStore already has data, skipping seed');
    return;
  }

  console.log('[seed] Populating WorkoutStore with initial data...');

  // ==========================================
  // ВСПОМОГАТЕЛЬНАЯ: создание варианта
  // ==========================================
  // Карта названий оборудования → equipmentId
  const EQ = {
    'штанга':             'eq-barbell',
    'гантели':            'eq-dumbbell',
    'гиря':               'eq-kettlebell',
    'тренажёр':           'eq-machine',
    'кроссовер':          'eq-crossover',
    'резинка':            'eq-band',
    'канат':              'eq-rope',
    'турник':             'eq-bar',
    'брусья':             'eq-parallel-bars',
    'коврик':             'eq-mat',
    'фитбол':             'eq-fitball',
    'скамья':             'eq-bench',
    'степ-платформа':     'eq-step',
    'эспандер':           'eq-expander',
    'ролл':               'eq-foam-roller',
    'без оборудования':   'eq-bodyweight'
  };

  function seedV(name, baseName, loadType, muscleIds, equipmentName) {
    // Ищем или создаём базовое упражнение
    let base = WorkoutStore.getBaseExercises().find(b => b.name === baseName);
    if (!base) {
      base = WorkoutStore.addBaseExercise({ name: baseName, muscleCategoryIds: muscleIds });
    }
    
    // Создаём вариант
    return WorkoutStore.addVariant({
      name: name,
      baseExerciseId: base.id,
      loadType: loadType,
      muscleIds: muscleIds,
      equipmentId: EQ[equipmentName] || ''
    });
  }

  // ==========================================
  // 🏋️ ГРУДЬ (muscle-chest)
  // ==========================================
  const chest = ['muscle-chest'];

  seedV('Жим лежа · штанга',                'Жим лежа',           'strength', chest, 'штанга');
  seedV('Жим лежа · гантели',               'Жим лежа',           'strength', chest, 'гантели');
  seedV('Жим лежа (наклон) · штанга',       'Жим лежа',           'strength', chest, 'штанга');
  seedV('Жим лежа (наклон) · гантели',      'Жим лежа',           'strength', chest, 'гантели');
  seedV('Разводка гантелей лежа',           'Разводка гантелей',  'strength', chest, 'гантели');
  seedV('Сведения в кроссовере',             'Сведения в кроссовере', 'strength', chest, 'кроссовер');
  seedV('Отжимания от пола (грудь)',         'Отжимания',          'bodyweight', chest, 'без оборудования');
  seedV('Отжимания на брусьях (грудь)',      'Отжимания на брусьях', 'bodyweight', chest, 'брусья');
  seedV('Жим в тренажёре (грудь)',           'Жим в тренажёре',    'strength', chest, 'тренажёр');
  seedV('Пулловер с гантелью',               'Пулловер',           'strength', chest, 'гантели');

  // ==========================================
  // 🔙 СПИНА (muscle-back)
  // ==========================================
  const back = ['muscle-back'];

  seedV('Тяга штанги в наклоне',             'Тяга в наклоне',     'strength', back, 'штанга');
  seedV('Тяга гантели в наклоне',            'Тяга в наклоне',     'strength', back, 'гантели');
  seedV('Тяга верхнего блока (широкий)',     'Тяга верхнего блока','strength', back, 'тренажёр');
  seedV('Тяга верхнего блока (узкий)',       'Тяга верхнего блока','strength', back, 'тренажёр');
  seedV('Тяга горизонтального блока',        'Тяга блока',         'strength', back, 'тренажёр');
  seedV('Подтягивания (широкий хват)',        'Подтягивания',       'bodyweight', back, 'турник');
  seedV('Подтягивания (обратный хват)',       'Подтягивания',       'bodyweight', back, 'турник');
  seedV('Подтягивания (узкий хват)',          'Подтягивания',       'bodyweight', back, 'турник');
  seedV('Тяга штанги к поясу',               'Тяга к поясу',       'strength', back, 'штанга');
  seedV('Гиперэкстензия',                     'Гиперэкстензия',     'bodyweight', back, 'скамья');
  seedV('Становая тяга',                      'Становая тяга',      'strength', [...back, 'muscle-legs'], 'штанга');
  seedV('Румынская тяга',                     'Румынская тяга',     'strength', back, 'штанга');
  seedV('Шраги с гантелями',                  'Шраги',              'strength', back, 'гантели');

  // ==========================================
  // 🦵 НОГИ (muscle-legs)
  // ==========================================
  const legs = ['muscle-legs'];

  seedV('Приседания со штангой',              'Приседания',         'strength', legs, 'штанга');
  seedV('Приседания в тренажёре Смита',       'Приседания',         'strength', legs, 'тренажёр');
  seedV('Приседания с гантелями',             'Приседания',         'strength', legs, 'гантели');
  seedV('Жим ногами в тренажёре',             'Жим ногами',         'strength', legs, 'тренажёр');
  seedV('Разгибание ног в тренажёре',         'Разгибание ног',     'strength', legs, 'тренажёр');
  seedV('Сгибание ног в тренажёре',           'Сгибание ног',       'strength', legs, 'тренажёр');
  seedV('Выпады с гантелями',                 'Выпады',             'strength', legs, 'гантели');
  seedV('Выпады со штангой',                  'Выпады',             'strength', legs, 'штанга');
  seedV('Подъём на носки стоя',               'Подъём на носки',    'bodyweight', legs, 'без оборудования');
  seedV('Подъём на носки сидя',               'Подъём на носки',    'strength', legs, 'тренажёр');
  seedV('Ягодичный мостик',                   'Ягодичный мостик',   'bodyweight', legs, 'коврик');
  seedV('Болгарские сплит-приседания',        'Болгарские приседания', 'strength', legs, 'гантели');

  // ==========================================
  // 🏋️ ПЛЕЧИ (muscle-shoulders)
  // ==========================================
  const shoulders = ['muscle-shoulders'];

  seedV('Жим штанги стоя (армейский)',        'Жим стоя',           'strength', shoulders, 'штанга');
  seedV('Жим гантелей сидя',                  'Жим сидя',           'strength', shoulders, 'гантели');
  seedV('Махи гантелями в стороны',           'Махи в стороны',     'strength', shoulders, 'гантели');
  seedV('Махи гантелями перед собой',         'Махи перед собой',   'strength', shoulders, 'гантели');
  seedV('Махи гантелями в наклоне (задняя дельта)', 'Махи в наклоне','strength', shoulders, 'гантели');
  seedV('Тяга штанги к подбородку',           'Тяга к подбородку',  'strength', shoulders, 'штанга');
  seedV('Разводка гантелей в наклоне',        'Разводка в наклоне', 'strength', shoulders, 'гантели');
  seedV('Подъём гантелей через стороны',      'Подъём гантелей',    'strength', shoulders, 'гантели');
  seedV('Арнольд-жим',                        'Арнольд-жим',        'strength', shoulders, 'гантели');

  // ==========================================
  // 💪 РУКИ (muscle-arms)
  // ==========================================
  const arms = ['muscle-arms'];

  // Бицепс
  seedV('Подъём штанги на бицепс',            'Подъём на бицепс',   'strength', arms, 'штанга');
  seedV('Подъём гантелей на бицепс сидя',     'Подъём на бицепс',   'strength', arms, 'гантели');
  seedV('Молотки с гантелями',                'Молотки',            'strength', arms, 'гантели');
  seedV('Концентрированный подъём гантели',   'Концентрированный подъём', 'strength', arms, 'гантели');
  seedV('Сгибание рук в тренажёре (бицепс)',  'Сгибание рук',       'strength', arms, 'тренажёр');
  seedV('Подъём штанги на бицепс обратным хватом', 'Подъём обратным хватом', 'strength', arms, 'штанга');

  // Трицепс
  seedV('Французский жим лёжа',               'Французский жим',    'strength', arms, 'штанга');
  seedV('Французский жим сидя с гантелью',    'Французский жим',    'strength', arms, 'гантели');
  seedV('Разгибание рук на блоке (трицепс)',  'Разгибание на блоке','strength', arms, 'кроссовер');
  seedV('Отжимания от скамьи (трицепс)',      'Отжимания от скамьи','bodyweight', arms, 'скамья');
  seedV('Отжимания узким хватом',             'Отжимания (трицепс)','bodyweight', arms, 'без оборудования');
  seedV('Кикбэк с гантелью',                  'Кикбэк',             'strength', arms, 'гантели');

  // Предплечья
  seedV('Сгибание кистей со штангой',         'Сгибание кистей',    'strength', arms, 'штанга');
  seedV('Разгибание кистей со штангой',       'Разгибание кистей',  'strength', arms, 'штанга');

  // ==========================================
  // 🧘 КОРПУС (muscle-core)
  // ==========================================
  const core = ['muscle-core'];

  seedV('Планка',                              'Планка',             'bodyweight', core, 'коврик');
  seedV('Боковая планка',                      'Боковая планка',     'bodyweight', core, 'коврик');
  seedV('Скручивания на пресс',                'Скручивания',        'bodyweight', core, 'коврик');
  seedV('Подъём ног в висе',                   'Подъём ног',         'bodyweight', core, 'турник');
  seedV('Обратные скручивания',                'Обратные скручивания','bodyweight', core, 'коврик');
  seedV('Русский твист с гантелью',            'Русский твист',      'strength', core, 'гантели');
  seedV('Велосипед',                            'Велосипед',          'bodyweight', core, 'коврик');
  seedV('Дровосек с гантелью',                 'Дровосек',           'strength', core, 'гантели');
  seedV('Канат (cable crunch)',                'Канат на пресс',     'strength', core, 'кроссовер');

  // ==========================================
  // 🔥 ФУЛБОДИ (muscle-fullbody)
  // ==========================================
  const fullbody = ['muscle-fullbody'];

  seedV('Берпи',                               'Берпи',              'bodyweight', fullbody, 'без оборудования');
  seedV('Бёрпи с отжиманием',                  'Берпи',              'bodyweight', fullbody, 'без оборудования');
  seedV('Трастеры со штангой',                 'Трастеры',           'strength', fullbody, 'штанга');
  seedV('Трастеры с гантелями',                'Трастеры',           'strength', fullbody, 'гантели');
  seedV('Махи гирей',                          'Махи гирей',         'strength', fullbody, 'гиря');
  seedV('Бёрпи с прыжком',                     'Берпи',              'bodyweight', fullbody, 'без оборудования');

  // ==========================================
  // 🏃 КАРДИО (muscle-cardio)
  // ==========================================
  const cardio = ['muscle-cardio'];

  seedV('Беговая дорожка',                     'Бег',                'cardio', cardio, 'тренажёр');
  seedV('Интервальный бег',                    'Бег',                'cardio', cardio, 'тренажёр');
  seedV('Велотренажёр',                        'Велосипед',          'cardio', cardio, 'тренажёр');
  seedV('Эллипс',                              'Эллипс',             'cardio', cardio, 'тренажёр');
  seedV('Степпер',                             'Степпер',            'cardio', cardio, 'тренажёр');
  seedV('Гребной тренажёр',                    'Гребля',             'cardio', cardio, 'тренажёр');
  seedV('Скакалка',                            'Скакалка',           'cardio', cardio, 'без оборудования');
  seedV('Плавание',                            'Плавание',           'cardio', cardio, 'без оборудования');
  seedV('Ходьба',                              'Ходьба',             'cardio', cardio, 'без оборудования');

  // ==========================================
  // 📌 ДРУГОЕ (muscle-other)
  // ==========================================
  const other = ['muscle-other'];

  seedV('Растяжка (общая)',                    'Растяжка',           'other', other, 'коврик');
  seedV('Йога',                                'Йога',               'other', other, 'коврик');
  seedV('Пилатес',                             'Пилатес',            'other', other, 'коврик');
  seedV('Разминка (суставная)',               'Разминка',           'other', other, 'без оборудования');
  seedV('Зарядка',                             'Зарядка',            'other', other, 'без оборудования');

  console.log('[seed] Done! Added base exercises:', WorkoutStore.getBaseExercises().length,
              'variants:', WorkoutStore.getVariants().length);
}

